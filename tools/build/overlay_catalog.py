from __future__ import annotations

import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "companion/overlay/ui_text_catalog.inc"


def generate() -> str:
    make = (ROOT / "companion/overlay/Makefile").read_text(encoding="utf-8")
    units = re.search(r"^CFILES := (.+)$", make, re.M)[1].split()
    # Resolve exactly the production translation units, then their local headers.
    directories = [ROOT / p for p in ["companion/overlay", "companion", "common/protocol",
                   "common/time", "common/crypto", "platform/switch", "third_party/cjson", "companion/nro"]]
    pending = [next(d / name for d in directories if (d / name).exists()) for name in units]
    pending += list((ROOT / "companion/overlay/source").glob("*.cpp"))
    seen: set[Path] = set()
    used: set[str] = set()
    while pending:
        path = pending.pop().resolve()
        if path in seen:
            continue
        seen.add(path)
        text = path.read_text(encoding="utf-8")
        used.update(re.findall(r"\bPTC_UI_T_[A-Z0-9_]+\b", text))
        for include in re.findall(r'^\s*#include "([^"]+)"', text, re.M):
            if Path(include).suffix not in {".h", ".hpp"}:
                continue
            for base in [path.parent, ROOT, *directories]:
                target = base / include
                if target.is_file():
                    pending.append(target)
                    break
    catalogs = []
    for language in ["zh_hans", "zh_hant", "en"]:
        rows: dict[str, str] = {}
        for path in (ROOT / "companion/ui_text" / language).glob("*.inc"):
            rows.update(re.findall(r'^PTC_UI_TEXT_VALUE\((\w+), ("(?:\\.|[^"\\])*")\)$',
                                   path.read_text(encoding="utf-8"), re.M))
        catalogs.append(rows)
    keys = []
    for include in re.findall(r'#include "([^"]+)"', (ROOT / "companion/ui_text_keys.inc").read_text()):
        keys.extend(re.findall(r'PTC_UI_TEXT_KEY\((\w+)\)', (ROOT / "companion" / include).read_text()))
    unknown = used - set(keys)
    if unknown:
        raise ValueError(f"Unknown Overlay keys: {sorted(unknown)}")
    lines = ["// Generated by tools/build/overlay_catalog.py; stable global IDs, three languages."]
    for key in keys:
        if key in used:
            lines.append(f'PTC_OVERLAY_TEXT({key}, "{key}", ' + ", ".join(c[key] for c in catalogs) + ")")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != result:
            raise SystemExit("Overlay catalog stale: run python tools/build/overlay_catalog.py")
    elif not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != result:
        OUTPUT.write_text(result, encoding="utf-8")
    print(f"Overlay catalog: {result.count('PTC_OVERLAY_TEXT(')} keys")


if __name__ == "__main__":
    main()
